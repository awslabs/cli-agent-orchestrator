// Generates src/types.ts from ../schemas/*.json. `node scripts/gen-types.mjs --check` fails when
// the checked-in file is out of date (also covered by test/types.test.ts).
import { readFileSync, writeFileSync } from 'node:fs'
import { dirname, resolve } from 'node:path'
import { fileURLToPath } from 'node:url'

const here = dirname(fileURLToPath(import.meta.url))
const schemaDir = resolve(here, '../../schemas')
const out = resolve(here, '../src/types.ts')

const files = {
  'errors.schema.json': { root: 'ErrorEnvelope', defs: { error: 'ApiError' } },
  'shelf.schema.json': { root: 'ShelfResponse', defs: { relay: 'ShelfRelay' } },
  'history.schema.json': { root: 'HistoryResponse', defs: {} },
  'actions.schema.json': { root: null, defs: {} },
  'relays.schema.json': { root: null, defs: {} },
}
const cap = (s) => s[0].toUpperCase() + s.slice(1)
const nameOf = (file, def) => files[file].defs[def] ?? cap(def)

function refName(ref, file) {
  const [f, frag] = ref.split('#')
  const target = f || file
  const m = /^\/\$defs\/(.+)$/.exec(frag)
  if (!m) throw new Error(`unsupported $ref ${ref}`)
  return nameOf(target, m[1])
}

function ts(s, file, ind) {
  if (s.$ref) return refName(s.$ref, file)
  if (s.const !== undefined) return JSON.stringify(s.const)
  if (s.enum) return s.enum.map((v) => JSON.stringify(v)).join(' | ')
  if (s.oneOf) return s.oneOf.map((x) => ts(x, file, ind)).join(' | ')
  if (Array.isArray(s.type)) return s.type.map((t) => ts({ ...s, type: t }, file, ind)).join(' | ')
  switch (s.type) {
    case 'string': return 'string'
    case 'integer':
    case 'number': return 'number'
    case 'boolean': return 'boolean'
    case 'null': return 'null'
    case 'array': {
      const inner = ts(s.items ?? {}, file, ind)
      return /[|{]/.test(inner) ? `Array<${inner}>` : `${inner}[]`
    }
    case 'object': {
      if (!s.properties) return 'Record<string, unknown>'
      const req = new Set(s.required ?? [])
      const pad = '  '.repeat(ind + 1)
      const lines = Object.entries(s.properties).map(([k, v]) => {
        const doc = v.description ? `${pad}/** ${v.description.replace(/\*\//g, '* /')} */\n` : ''
        return `${doc}${pad}${k}${req.has(k) ? '' : '?'}: ${ts(v, file, ind + 1)}`
      })
      return `{\n${lines.join('\n')}\n${'  '.repeat(ind)}}`
    }
    default: return 'unknown'
  }
}

export function generate() {
  let body = '// GENERATED by scripts/gen-types.mjs from ../schemas/*.json. Do not edit by hand.\n/* eslint-disable */\n'
  for (const file of Object.keys(files)) {
    const schema = JSON.parse(readFileSync(resolve(schemaDir, file), 'utf8'))
    body += `\n// ${file}\n`
    for (const [d, s] of Object.entries(schema.$defs ?? {})) {
      const name = nameOf(file, d)
      const t = ts(s, file, 0)
      body += t.startsWith('{') ? `export interface ${name} ${t}\n\n` : `export type ${name} = ${t}\n\n`
    }
    const rootName = files[file].root
    if (rootName) body += `export interface ${rootName} ${ts(schema, file, 0)}\n\n`
  }
  return body.replace(/\n{3,}/g, '\n\n').trimEnd() + '\n'
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const text = generate()
  if (process.argv.includes('--check')) {
    let cur = ''
    try { cur = readFileSync(out, 'utf8') } catch { /* missing */ }
    if (cur !== text) { console.error('src/types.ts is out of date: run npm run gen:types'); process.exit(1) }
  } else {
    writeFileSync(out, text)
    console.log('wrote', out)
  }
}
